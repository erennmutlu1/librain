#!/usr/bin/env python3
"""Render docs/paper-source/architecture.html to docs/architecture.pdf.

Steps:
  1. Build the table of contents from the <h1>/<h2> headings inside <main> and write it into
     architecture.html between the TOC markers.
  2. Print the HTML to PDF with headless Google Chrome.
  3. Read back the page on which each heading landed (from the PDF's named destinations, which
     Chrome creates for every TOC link target), write those numbers into the TOC and print again.
     Repeat until the numbers stop changing.
  4. Set the PDF metadata (Title, Author, Subject).

Requirements: Google Chrome, Python 3.9+, and pypdf (pip install pypdf). poppler's pdftotext is
used as a fallback for finding headings if named destinations are missing.

Usage:
  python3 build_paper.py [--out PATH] [--chrome PATH] [--keep-toc]
"""
import argparse
import html
import logging
import os
import re
import shutil
import subprocess
import sys
import tempfile

logging.getLogger('pypdf').setLevel(logging.ERROR)  # Chrome PDFs trigger harmless xref warnings

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, 'architecture.html')
DEFAULT_OUT = os.path.normpath(os.path.join(HERE, '..', 'architecture.pdf'))
CHROME_CANDIDATES = [
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
    'google-chrome', 'google-chrome-stable', 'chromium', 'chromium-browser',
]
METADATA = {
    '/Title': 'LIBRAIN, A Multi-Agent RAG System for Scientific Discovery',
    '/Author': 'Eren Mutlu',
    '/Subject': 'Companion paper',
}
TOC_BEGIN = '<!-- TOC:BEGIN (generated by build_paper.py) -->'
TOC_END = '<!-- TOC:END -->'
MAX_PASSES = 6

HEADING_RE = re.compile(r'<h([12]) id="([^"]+)"([^>]*)>(.*?)</h\1>', re.S)


def find_chrome(explicit):
    for c in ([explicit] if explicit else []) + CHROME_CANDIDATES:
        path = c if os.path.isabs(c) else shutil.which(c)
        if path and os.path.exists(path):
            return path
    sys.exit('Google Chrome not found; pass --chrome PATH')


def headings(src):
    """(level, id, plain text) for every TOC heading inside <main>, in document order."""
    main = src[src.index('<main>'):src.index('</main>')]
    out = []
    for level, hid, attrs, inner in HEADING_RE.findall(main):
        if 'notoc' in attrs:
            continue
        text = html.unescape(re.sub(r'<[^>]+>', '', inner)).strip()
        out.append((int(level), hid, re.sub(r'\s+', ' ', text)))
    return out


def toc_html(entries, pages):
    rows = []
    for level, hid, text in entries:
        n = pages.get(hid, '')
        rows.append(f'  <a class="l{level}" href="#{hid}"><span class="t">{html.escape(text, quote=False)}</span>'
                    f'<span class="dots"></span><span class="n">{n}</span></a>')
    return '\n'.join(rows)


def write_toc(src, entries, pages):
    start = src.index(TOC_BEGIN) + len(TOC_BEGIN)
    end = src.index(TOC_END)
    return src[:start] + '\n' + toc_html(entries, pages) + '\n' + src[end:]


def render(chrome, html_path, pdf_path):
    profile = tempfile.mkdtemp(prefix='paper-chrome-')
    cmd = [chrome, '--headless=new', '--disable-gpu', '--no-pdf-header-footer',
           '--virtual-time-budget=20000', '--no-first-run', '--no-default-browser-check',
           f'--user-data-dir={profile}', f'--print-to-pdf={pdf_path}', 'file://' + html_path]
    try:
        proc = subprocess.Popen(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        try:
            proc.wait(timeout=180)
        except subprocess.TimeoutExpired:
            proc.kill()
            proc.wait()
            sys.exit('Chrome timed out')
    finally:
        # Chrome helpers normally exit with the parent; make sure none survive.
        subprocess.run(['pkill', '-f', profile], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        shutil.rmtree(profile, ignore_errors=True)
    if not os.path.exists(pdf_path) or os.path.getsize(pdf_path) == 0:
        sys.exit('Chrome did not produce a PDF')


def heading_pages(pdf_path, entries):
    """Map heading id -> 1-based page number."""
    from pypdf import PdfReader
    reader = PdfReader(pdf_path)
    pages = {}
    try:
        for name, dest in reader.named_destinations.items():
            pages[name.lstrip('/')] = reader.get_destination_page_number(dest) + 1
    except Exception:
        pass
    missing = [e for e in entries if e[1] not in pages]
    if missing:
        # Fallback: find the heading text at the start of a line, after the TOC pages.
        text = subprocess.run(['pdftotext', '-layout', pdf_path, '-'], capture_output=True, text=True).stdout
        page_texts = text.split('\f')
        first_body = 1 + max((i for i, t in enumerate(page_texts) if 'Contents' in t[:400]), default=0)
        for level, hid, title in missing:
            for i in range(first_body, len(page_texts)):
                lines = [re.sub(r'\s+', ' ', l.strip()) for l in page_texts[i].splitlines()]
                if any(l == title or l.startswith(title) for l in lines):
                    pages[hid] = i + 1
                    break
    return {hid: pages.get(hid, '?') for _, hid, _ in entries}


def set_metadata(pdf_path):
    from pypdf import PdfReader, PdfWriter
    reader = PdfReader(pdf_path)
    writer = PdfWriter(clone_from=reader)
    writer.add_metadata(METADATA)
    tmp = pdf_path + '.tmp'
    with open(tmp, 'wb') as fh:
        writer.write(fh)
    os.replace(tmp, pdf_path)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out', default=DEFAULT_OUT, help='output PDF (default: docs/architecture.pdf)')
    ap.add_argument('--chrome', help='path to the Chrome binary')
    ap.add_argument('--keep-toc', action='store_true', help='render once with the TOC as it is; no page passes')
    args = ap.parse_args()

    chrome = find_chrome(args.chrome)
    out = os.path.abspath(args.out)
    work = tempfile.mkdtemp(prefix='paper-build-')
    tmp_pdf = os.path.join(work, 'paper.pdf')
    try:
        src = open(SOURCE, encoding='utf-8').read()
        entries = headings(src)
        if args.keep_toc:
            render(chrome, SOURCE, tmp_pdf)
        else:
            # Start from the numbers already in the file so a no-op rebuild converges in one pass.
            current = dict(re.findall(r'href="#([^"]+)"><span class="t">.*?<span class="n">([^<]*)</span>', src))
            pages = {hid: current.get(hid, '') for _, hid, _ in entries}
            for n in range(1, MAX_PASSES + 1):
                new_src = write_toc(src, entries, pages)
                if new_src != src:
                    with open(SOURCE, 'w', encoding='utf-8') as fh:
                        fh.write(new_src)
                    src = new_src
                render(chrome, SOURCE, tmp_pdf)
                found = heading_pages(tmp_pdf, entries)
                found = {k: str(v) for k, v in found.items()}
                changed = {k for k in found if found[k] != str(pages.get(k, ''))}
                print(f'pass {n}: {len(changed)} TOC page numbers changed')
                if not changed:
                    break
                pages = found
            else:
                sys.exit('TOC page numbers did not stabilise')
            if '?' in pages.values():
                print('warning: headings not found in PDF:', [k for k, v in pages.items() if v == '?'])
        set_metadata(tmp_pdf)
        shutil.copyfile(tmp_pdf, out)
        from pypdf import PdfReader
        print(f'wrote {out} ({len(PdfReader(out).pages)} pages)')
    finally:
        shutil.rmtree(work, ignore_errors=True)


if __name__ == '__main__':
    main()
